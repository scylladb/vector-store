SSH_USER = "ubuntu"
SSH_FAILED = 255  # ssh's own exit code for connection/authentication failures
CONTROL_PREFIX = "vsb-"
# ControlPath `<dir>/vsb-%C`: %C is 40 hex chars and ssh appends ".<16 chars>"
# while binding; keep the socket path < 100 bytes (sun_path: 104 macOS, 108 Linux).
MAX_CONTROL_PATH = 100
_CONTROL_EXTRA = 1 + len(CONTROL_PREFIX) + 40 + 17
CHECKIP_URL = "https://checkip.amazonaws.com"
MAX_PARALLEL = 16
MAX_SCRIPT_BYTES = 100_000  # node scripts travel as one argv string (limit 128 KiB)
LARGE_UPLOAD_BYTES = 8 * 1024 * 1024
WAIT_SSH_ATTEMPT_TIMEOUT_S = 30
WAIT_SSH_RETRY_S = 5

JOB_RUNNER = "job-run.sh"
JOB_UNIT_PREFIX = "vsbench-job-"
JOB_POLL_SECONDS = 2.0
JOB_POLL_CHUNK_BYTES = 4 * 1024 * 1024
JOB_STOP_TIMEOUT_S = 60
JOB_CANCELLED_EXIT = 143
MAX_POLL_FAILURES = 3  # consecutive failed polls tolerated by job_follow
_ACTIVE_STATES = ("active", "activating", "deactivating", "reloading", "refreshing")

_ENV_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_NODE_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
_JOB_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")
