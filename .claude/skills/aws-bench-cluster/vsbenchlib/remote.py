_SCRIPT_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_MODE_RE = re.compile(r"^[0-7]{3,4}$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_INSTANCE_ID_RE = re.compile(r"^i-[0-9a-f]+$")
